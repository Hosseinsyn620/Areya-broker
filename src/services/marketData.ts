export interface OrderBookEntry {
  price: number;
  amount: number;
  total: number;
  percent: number;
}

export interface TradeTick {
  id: string;
  price: number;
  amount: number;
  side: 'buy' | 'sell';
  time: number;
}

/**
 * Generate synthetic historical candles based on current price
 */
export function generateCandles(currentPrice: number, count = 80, timeframe = '15m'): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  
  let tfMinutes = 15;
  if (timeframe === '1m') tfMinutes = 1;
  else if (timeframe === '5m') tfMinutes = 5;
  else if (timeframe === '15m') tfMinutes = 15;
  else if (timeframe === '1h') tfMinutes = 60;
  else if (timeframe === '4h') tfMinutes = 240;
  else if (timeframe === '1D') tfMinutes = 1440;

  const stepMs = tfMinutes * 60 * 1000;
  
  // Volatility scale
  const volatility = currentPrice * 0.0035;

  let lastClose = currentPrice * (1 - (Math.random() * 0.04 - 0.02));

  for (let i = count; i >= 0; i--) {
    const time = now - i * stepMs;
    const change = (Math.random() - 0.49) * volatility;
    const open = lastClose;
    let close = open + change;
    if (i === 0) close = currentPrice; // lock latest to current price

    const high = Math.max(open, close) + Math.random() * volatility * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8;
    const volume = Math.floor(Math.random() * 50 + 10) * (currentPrice > 1000 ? 5 : 500);

    candles.push({
      time,
      open,
      high,
      low,
      close,
      volume,
    });

    lastClose = close;
  }

  return candles;
}

/**
 * Generate simulated Order Book around current price
 */
export function generateOrderBook(price: number, precision: number): { bids: OrderBookEntry[]; asks: OrderBookEntry[]; spread: number } {
  const asks: OrderBookEntry[] = [];
  const bids: OrderBookEntry[] = [];

  const spread = price * 0.0003;
  let runningAskTotal = 0;
  let runningBidTotal = 0;

  const step = price > 1000 ? Math.max(1, price * 0.0002) : price * 0.0004;

  // Asks (Sells above current price)
  for (let i = 1; i <= 9; i++) {
    const askPrice = price + spread / 2 + i * step;
    const amount = Number((Math.random() * 2.5 + 0.2).toFixed(3));
    runningAskTotal += amount;
    asks.push({
      price: Number(askPrice.toFixed(precision)),
      amount,
      total: runningAskTotal,
      percent: 0,
    });
  }

  // Calculate ask percentages
  asks.forEach(a => a.percent = Math.min(100, Math.round((a.total / runningAskTotal) * 100)));

  // Bids (Buys below current price)
  for (let i = 1; i <= 9; i++) {
    const bidPrice = price - spread / 2 - i * step;
    const amount = Number((Math.random() * 2.5 + 0.2).toFixed(3));
    runningBidTotal += amount;
    bids.push({
      price: Number(bidPrice.toFixed(precision)),
      amount,
      total: runningBidTotal,
      percent: 0,
    });
  }

  bids.forEach(b => b.percent = Math.min(100, Math.round((b.total / runningBidTotal) * 100)));

  return {
    asks: asks.reverse(), // Highest ask at top
    bids,
    spread: Number(spread.toFixed(precision)),
  };
}

/**
 * Generate initial recent trades list
 */
export function generateInitialTrades(price: number, precision: number): TradeTick[] {
  const trades: TradeTick[] = [];
  const now = Date.now();

  for (let i = 0; i < 15; i++) {
    const isBuy = Math.random() > 0.48;
    const delta = (Math.random() - 0.5) * (price * 0.001);
    const tickPrice = Number((price + delta).toFixed(precision));
    const amount = Number((Math.random() * 1.8 + 0.05).toFixed(3));

    trades.push({
      id: `trade_${now - i * 1500}`,
      price: tickPrice,
      amount,
      side: isBuy ? 'buy' : 'sell',
      time: now - i * 2000,
    });
  }

  return trades;
}
